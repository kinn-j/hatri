"""Generate a versioned, offline Hindi draft pack from the audited English corpus.

Generation tool only: the web app never downloads a translation model.
The model and Python dependencies are external development tools, not Hatri
runtime dependencies. Translators must review the resulting text, particularly
the measurements and cooking safety instructions, before marking it approved.

Usage: python scripts/build-hindi-pack.py /tmp/hatri-hindi-corpus.json \
       /tmp/hatri-hindi-progress.json hindi-catalog.js
"""

import json
import re
import sys
import time
from pathlib import Path

from bhashantar import Translator


FRACTIONS = {
    "¼": "1/4", "½": "1/2", "¾": "3/4", "⅓": "1/3", "⅔": "2/3",
    "⅛": "1/8", "⅜": "3/8", "⅝": "5/8", "⅞": "7/8", "⅙": "1/6",
}


def prepare(source):
    # IndicTrans2's tokenizer misreads typographic fractions as e.g. 1.4.
    # A slash fraction has the exact same mathematical value and is safer.
    text = source
    for glyph, normal in FRACTIONS.items():
        text = text.replace(glyph, normal)
    return text


def output_file(corpus, translated, destination):
    # Only shipped translations (no source lists/model weights) are included.
    keys = ["interfaceText", "titles", "ingredients", "amounts", "steps"]
    pack = {}
    for kind in keys:
        pack[kind] = {source: translated[source] for source in corpus[kind]
                      if translated.get(source) and translated[source] != source}
    total = sum(len(value) for value in pack.values())
    content = ("/* Offline Hindi translation draft; generated by scripts/build-hindi-pack.py.\n"
               " * Each translation is paired with its original English source.\n"
               " * Review cooking steps and quantities before using them for food safety decisions.\n"
               " */\n"
               "globalThis.HATRI_HINDI_CATALOG = "
               + json.dumps(pack, ensure_ascii=False, separators=(",", ":")) + ";\n")
    destination.write_text(content, encoding="utf-8")
    return total


def main():
    if len(sys.argv) != 4:
        raise SystemExit("Usage: build-hindi-pack.py CORPUS_JSON PROGRESS_JSON OUTPUT_JS")
    corpus_path, progress_path, output_path = map(Path, sys.argv[1:])
    corpus = json.loads(corpus_path.read_text(encoding="utf-8"))
    translated = json.loads(progress_path.read_text(encoding="utf-8")) if progress_path.exists() else {}
    keys = ["interfaceText", "ingredients", "titles", "amounts", "steps"]
    ordered = list(dict.fromkeys(source for kind in keys for source in corpus[kind]))
    pending = [source for source in ordered if source not in translated]
    print(f"{len(pending)} pending of {len(ordered)} strings", flush=True)
    translator = Translator(threads=4, beam_size=4, max_batch_size=16)
    start = time.monotonic()
    for offset in range(0, len(pending), 64):
        group = pending[offset:offset + 64]
        try:
            output = translator.translate([prepare(source) for source in group])
        except Exception as error:
            raise RuntimeError(f"Translation failed at batch {offset}: {error}") from error
        if len(output) != len(group):
            raise RuntimeError(f"Translator returned {len(output)} entries for {len(group)} inputs")
        for source, value in zip(group, output):
            translated[source] = value.strip()
        progress_path.write_text(json.dumps(translated, ensure_ascii=False), encoding="utf-8")
        completed = min(offset + len(group), len(pending))
        if completed % 256 == 0 or completed == len(pending):
            elapsed = round(time.monotonic() - start)
            print(f"{completed}/{len(pending)} translated in {elapsed}s", flush=True)
    count = output_file(corpus, translated, output_path)
    print(f"Wrote {count} Hindi phrases to {output_path}", flush=True)


if __name__ == "__main__":
    main()
